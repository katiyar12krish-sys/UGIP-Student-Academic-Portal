// =====================================================================================================
// npm run schema  ->  writes database/sqlite/full-schema.sql
// -----------------------------------------------------------------------------------------------------
// Builds an EMPTY database in a temporary folder exactly the way the server does on start (all schema files
// plus the tables that some route files create), then writes every CREATE TABLE / CREATE INDEX / trigger
// statement - with the comments as they were written - into one file. That file is the complete, current
// map of the database: open it to see every table and what each column means.
// =====================================================================================================
import fs from 'fs';
import os from 'os';
import path from 'path';

process.env.PORTAL_DATA_DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'ugip-schema-'));   // never touches the real data
const { db } = await import('../db/connection');
await import('../routes/records');          // creates the Step 20 tables
await import('../routes/resumes');          // creates the resume table

const rows = db.prepare(`SELECT type, name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'
  ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 ELSE 2 END, rowid`).all() as any[];
const tables = rows.filter((r) => r.type === 'table');
const out = [
  '-- =====================================================================================================',
  '-- UGIP portal - COMPLETE database layout (SQLite), made from the live schema by `npm run schema`.',
  `-- ${tables.length} tables. Do not edit this file by hand: change server/db/schema*.sql (or the route that`,
  '-- creates the table) and run `npm run schema` again. Every table and column is explained in the comments.',
  '-- =====================================================================================================',
  '',
  ...rows.map((r) => r.sql.trim() + ';\n'),
];
const target = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '../../database/sqlite/full-schema.sql');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out.join('\n'));
console.log(`Wrote ${tables.length} tables to ${target}`);
